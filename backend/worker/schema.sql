CREATE TABLE IF NOT EXISTS orders (
 id TEXT PRIMARY KEY, token TEXT NOT NULL, created INTEGER NOT NULL,
 code TEXT NOT NULL, tries INTEGER NOT NULL DEFAULT 0, verified INTEGER NOT NULL DEFAULT 0,
 body TEXT NOT NULL, digest TEXT NOT NULL, accepted_at INTEGER,
 customer TEXT UNIQUE, session TEXT UNIQUE, state TEXT NOT NULL DEFAULT 'draft'
);
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, kind TEXT NOT NULL, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS jobs (
 id TEXT PRIMARY KEY, order_id TEXT NOT NULL REFERENCES orders(id), kind TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending', created INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS jobs_pending ON jobs(state,created);
CREATE TABLE IF NOT EXISTS rates (subject TEXT, period INTEGER, count INTEGER NOT NULL, PRIMARY KEY(subject,period));
